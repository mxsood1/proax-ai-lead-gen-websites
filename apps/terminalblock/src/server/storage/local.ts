import "server-only";
import { mkdir, readdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { config } from "@/server/config";
import { summarize, type Lead, type LeadFile } from "@/server/leads/types";
import { newId, safeFileName } from "@/server/rfq/ref";
import type { IncomingFile, LeadStore } from "./types";

/**
 * Development store: one JSON file per lead in .data/leads and uploads in
 * .data/uploads/<leadId>/. The .data folder is git-ignored.
 */
const leadsDir = () => path.join(config.dataDir, "leads");
const uploadsDir = () => path.join(config.dataDir, "uploads");
const UUID = /^[0-9a-f-]{36}$/i;

async function writeJsonAtomic(file: string, data: unknown) {
  await mkdir(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  await writeFile(tmp, JSON.stringify(data, null, 2), "utf8");
  await rename(tmp, file);
}

// Serialize writes per lead so concurrent updates don't clobber each other.
const queues = new Map<string, Promise<unknown>>();
function serialize<T>(id: string, fn: () => Promise<T>): Promise<T> {
  const prev = queues.get(id) ?? Promise.resolve();
  const next = prev.then(fn, fn);
  queues.set(id, next.catch(() => {}));
  return next;
}

export const localStore: LeadStore = {
  kind: "local",

  async create(lead) {
    await writeJsonAtomic(path.join(leadsDir(), `${lead.id}.json`), lead);
  },

  async get(id) {
    if (!UUID.test(id)) return null;
    try {
      return JSON.parse(await readFile(path.join(leadsDir(), `${id}.json`), "utf8")) as Lead;
    } catch {
      return null;
    }
  },

  async list() {
    let names: string[] = [];
    try {
      names = (await readdir(leadsDir())).filter((n) => n.endsWith(".json"));
    } catch {
      return [];
    }
    const leads = await Promise.all(names.map((n) => this.get(n.replace(/\.json$/, ""))));
    return leads
      .filter((l): l is Lead => l !== null)
      .map(summarize)
      .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
  },

  update(id, change) {
    return serialize(id, async () => {
      const current = await this.get(id);
      if (!current) return null;
      const next = change(current);
      await writeJsonAtomic(path.join(leadsDir(), `${id}.json`), next);
      return next;
    });
  },

  async saveFile(leadId, file: IncomingFile): Promise<LeadFile> {
    const id = newId();
    const key = path.posix.join(leadId, `${id}-${safeFileName(file.name)}`);
    const full = path.join(uploadsDir(), key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, file.bytes);
    return { id, name: file.name.slice(0, 200), size: file.bytes.byteLength, type: file.type || "application/octet-stream", key };
  },

  async readFile(file) {
    // Keys are generated by saveFile; still refuse anything that escapes the uploads folder.
    const full = path.resolve(uploadsDir(), file.key);
    if (!full.startsWith(path.resolve(uploadsDir()) + path.sep)) return null;
    try {
      return new Uint8Array(await readFile(full));
    } catch {
      return null;
    }
  },
};
